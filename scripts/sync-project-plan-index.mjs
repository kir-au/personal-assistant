import fs from 'fs/promises';
import path from 'path';

const VAULT_ROOT = path.resolve(process.env.PERSONAL_VAULT_ROOT || path.join(process.env.HOME || '', 'personal-vault'));
const PROJECTS_ROOT = path.join(VAULT_ROOT, 'structured', 'projects');
const OUTPUT_PATH = path.join(VAULT_ROOT, 'structured', 'plans', 'planner-items.json');

function parseMetadata(block) {
  return Object.fromEntries(
    block
      .split('\n')
      .map((line) => line.trim())
      .filter(Boolean)
      .map((line) => {
        const separator = line.indexOf(':');
        return separator === -1
          ? [line, '']
          : [line.slice(0, separator).trim(), line.slice(separator + 1).trim()];
      })
  );
}

function field(body, name) {
  const match = body.match(new RegExp(`^\\*\\*${name}:\\*\\*\\s*(.+)$`, 'mi'));
  return match?.[1]?.trim();
}

function taskDescription(body) {
  return body
    .replace(/\n?\*\*(Why|Outcome|Source):\*\*[\s\S]*$/mi, '')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join(' ')
    .trim();
}

function parsePlan(markdown, relativePath) {
  const projectMatch = markdown.match(/^project:\s*(.+)$/mi);
  const titleMatch = markdown.match(/^title:\s*(.+)$/mi);
  const projectId = projectMatch?.[1]?.trim();
  const projectTitle = titleMatch?.[1]?.trim();
  if (!projectId || !projectTitle) return [];

  const taskPattern = /^###\s+(.+?)\n<!--\s*personal-vault-task\n([\s\S]*?)\n-->\n([\s\S]*?)(?=^###\s+|(?![\s\S]))/gm;
  const tasks = [];
  for (const match of markdown.matchAll(taskPattern)) {
    const metadata = parseMetadata(match[2]);
    if (!metadata.id) continue;
    const body = match[3].trim();
    tasks.push({
      id: metadata.id,
      title: match[1].trim(),
      area: metadata.area || projectTitle,
      projectId,
      status: metadata.status || 'planned',
      date: metadata.date || undefined,
      horizon: metadata.horizon || 'this-week',
      priority: Number(metadata.priority || 50),
      completedDate: metadata.completedDate || undefined,
      source: field(body, 'Source') || relativePath,
      detail: taskDescription(body),
      why: field(body, 'Why') || undefined,
      outcome: field(body, 'Outcome') || undefined,
      planPath: relativePath,
    });
  }
  return tasks;
}

export async function syncProjectPlanIndex() {
  let directories = [];
  try {
    directories = await fs.readdir(PROJECTS_ROOT, { withFileTypes: true });
  } catch {
    directories = [];
  }

  const items = [];
  for (const entry of directories.filter((item) => item.isDirectory())) {
    const absolutePath = path.join(PROJECTS_ROOT, entry.name, 'current-plan.md');
    const relativePath = path.posix.join('structured', 'projects', entry.name, 'current-plan.md');
    try {
      items.push(...parsePlan(await fs.readFile(absolutePath, 'utf-8'), relativePath));
    } catch {
      // A project can exist without a current plan yet.
    }
  }

  const payload = {
    title: 'Planner item index',
    description: 'Generated from each project current-plan.md. Do not edit this file directly.',
    generatedAt: new Date().toISOString(),
    source: 'structured/projects/*/current-plan.md',
    items: items.sort((a, b) => b.priority - a.priority || a.title.localeCompare(b.title)),
  };
  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, JSON.stringify(payload, null, 2) + '\n', 'utf-8');
  return payload;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const payload = await syncProjectPlanIndex();
  console.log(`Indexed ${payload.items.length} current project priorities.`);
}
